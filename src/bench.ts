// Memory benchmark: upload N MiB through the tus server (in a child process) into the in-process fake
// S3, sampling the server process's memory after a forced GC every 50 ms, so the numbers show live
// memory and not garbage waiting for collection.
// usage: node dist/src/bench.js <MiB> [partMiB]   (data goes to .tmp/bench-*, removed at the end)
import { fork } from "node:child_process";
import { createHash, randomBytes } from "node:crypto";
import { rm } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { upload, type Source } from "./client.js";
import { S3Client } from "./s3.js";
import { startServer } from "./server.js";
import { UploadStore } from "./store.js";
import { FakeS3 } from "./testing/fakes3.js";

const MIB = 1024 * 1024;
const CREDS = { accessKeyId: "BENCHKEY", secretAccessKey: "bench-only-secret" };

interface Peak {
  baseRssMiB: number;
  peakRssMiB: number;
  baseLiveMiB: number;
  peakLiveMiB: number;
}

/** Deterministic generated bytes: a random 1 MiB block with each MiB stamped with its index. */
function generated(size: number): Source {
  const block = randomBytes(MIB);
  return {
    size,
    read: (start, end) => {
      const out = Buffer.allocUnsafe(end - start);
      for (let pos = start; pos < end; ) {
        const mib = Math.floor(pos / MIB);
        const within = pos % MIB;
        const n = Math.min(MIB - within, end - pos);
        block.copy(out, pos - start, within, within + n);
        // Stamp the first 4 bytes of every MiB so misordered parts change the hash.
        for (let i = within; i < 4 && i < within + n; i++) out[pos - start + i - within] = (mib >> (8 * i)) & 0xff;
        pos += n;
      }
      return Promise.resolve(out);
    },
  };
}

/** Live memory (heap + buffers) after a forced GC, in MiB. */
function live(): number {
  (globalThis as { gc?: () => void }).gc?.();
  const m = process.memoryUsage();
  return (m.heapUsed + m.external + m.arrayBuffers) / MIB;
}

/** Child process: runs the tus server and reports memory peaks when asked. */
async function child(endpoint: string, dir: string, partSize: number): Promise<void> {
  const s3 = new S3Client({ endpoint, region: "us-east-1", bucket: "bench", credentials: CREDS });
  const server = await startServer({ s3, store: new UploadStore(join(dir, "state")), partSize, maxSize: 1024 * MIB });
  const peak: Peak = { baseRssMiB: process.memoryUsage().rss / MIB, peakRssMiB: 0, baseLiveMiB: live(), peakLiveMiB: 0 };
  const timer = setInterval(() => {
    peak.peakLiveMiB = Math.max(peak.peakLiveMiB, live());
    peak.peakRssMiB = Math.max(peak.peakRssMiB, process.memoryUsage().rss / MIB);
  }, 50);
  process.send?.({ url: server.url });
  process.on("message", () => {
    clearInterval(timer);
    process.send?.({ peak });
    server.close().then(
      () => process.exit(0),
      () => process.exit(1),
    );
  });
}

/** Parent: fake S3 + client; the server runs in a forked child. */
async function parent(sizeMiB: number, partMiB: number): Promise<void> {
  const dir = join(process.cwd(), ".tmp", `bench-${randomBytes(4).toString("hex")}`);
  const fake = new FakeS3({ dir: join(dir, "s3"), bucket: "bench", credentials: CREDS });
  try {
    const endpoint = await fake.start();
    const proc = fork(fileURLToPath(import.meta.url), ["--child", endpoint, dir, String(partMiB * MIB)], {
      execArgv: ["--expose-gc"],
    });
    const messages: { url?: string; peak?: Peak }[] = [];
    const next = (): Promise<{ url?: string; peak?: Peak }> =>
      new Promise((resolve, reject) => {
        const shifted = messages.shift();
        if (shifted) return resolve(shifted);
        proc.once("message", (m) => resolve(m as { url?: string; peak?: Peak }));
        proc.once("exit", (code) => reject(new Error(`server exited with ${code}`)));
      });
    const { url } = await next();
    const source = generated(sizeMiB * MIB);
    const started = performance.now();
    const result = await upload({ endpoint: `${url}/files`, source, chunkSize: 8 * MIB });
    const seconds = (performance.now() - started) / 1000;
    proc.send("stop");
    const { peak } = await next();
    const expected = createHash("sha256");
    for (let at = 0; at < source.size; at += 8 * MIB) expected.update(await source.read(at, Math.min(at + 8 * MIB, source.size)));
    const obj = [...fake.objects.values()][0];
    const r = (n: number): number => Number(n.toFixed(1));
    console.log(
      JSON.stringify({
        sizeMiB,
        partMiB,
        parts: fake.partSizes.length,
        seconds: Number(seconds.toFixed(2)),
        throughputMiBs: r(sizeMiB / seconds),
        serverBaseRssMiB: r(peak?.baseRssMiB ?? 0),
        serverPeakRssMiB: r(peak?.peakRssMiB ?? 0),
        serverBaseLiveMiB: r(peak?.baseLiveMiB ?? 0),
        serverPeakLiveMiB: r(peak?.peakLiveMiB ?? 0),
        intact: obj?.sha256 === expected.digest("hex") && obj.size === source.size,
        resumes: result.resumes,
      }),
    );
  } finally {
    await fake.stop();
    await rm(dir, { recursive: true, force: true });
  }
}

/** Parses arguments and runs the parent or child role. */
async function main(): Promise<void> {
  if (process.argv[2] === "--child") {
    return child(process.argv[3] ?? "", process.argv[4] ?? "", Number(process.argv[5]));
  }
  const sizeMiB = Number(process.argv[2] ?? "32");
  const partMiB = Number(process.argv[3] ?? "5");
  if (!Number.isInteger(sizeMiB) || sizeMiB < 1 || sizeMiB > 1024) throw new Error("size must be 1..1024 MiB");
  if (!Number.isInteger(partMiB) || partMiB < 5 || partMiB > 64) throw new Error("part size must be 5..64 MiB");
  return parent(sizeMiB, partMiB);
}

main().catch((err: unknown) => {
  console.error(err);
  process.exit(1);
});
